export const GLYPH_WIDTH = 5;
export const GLYPH_HEIGHT = 7;
/** Advance per character including the 1px gap. */
export const CHAR_ADVANCE = GLYPH_WIDTH + 1;
/** Advance per line including the 2px gap. */
export const LINE_ADVANCE = GLYPH_HEIGHT + 2;

type Bitmap = boolean[][];

const CACHE = new Map<string, Bitmap>();

function bitmap(char: string): Bitmap {
  const key = char.toUpperCase();
  const cached = CACHE.get(key);
  if (cached) return cached;
  const rows = GLYPHS[key] ?? GLYPHS['?'];
  const parsed = rows.map((row) => [...row].map((c) => c === '#'));
  CACHE.set(key, parsed);
  return parsed;
}

export interface TextOptions {
  /** Integer pixel multiplier. */
  scale?: number;
  /** 'left' | 'center' | 'right', relative to x. */
  align?: 'left' | 'center' | 'right';
  /** Extra pixels between characters. */
  tracking?: number;
}

/** Pixel width a string will occupy at the given scale. */
export function textWidth(text: string, options: TextOptions = {}): number {
  const { scale = 1, tracking = 0 } = options;
  if (text.length === 0) return 0;
  return (text.length * (CHAR_ADVANCE + tracking) - 1 - tracking) * scale;
}

/**
 * Draws `text` with its top-left at (x, y) in screen pixels.
 * Snaps to the pixel grid so glyphs never land on half pixels.
 */
export function drawText(
  ctx: CanvasRenderingContext2D,
  text: string,
  x: number,
  y: number,
  color: string,
  options: TextOptions = {},
): void {
  const { scale = 1, align = 'left', tracking = 0 } = options;
  const width = textWidth(text, options);
  let cursor = Math.round(
    align === 'center' ? x - width / 2 : align === 'right' ? x - width : x,
  );
  const top = Math.round(y);

  ctx.fillStyle = color;
  for (const char of text) {
    const rows = bitmap(char);
    for (let row = 0; row < rows.length; row++) {
      for (let col = 0; col < rows[row].length; col++) {
        if (!rows[row][col]) continue;
        ctx.fillRect(cursor + col * scale, top + row * scale, scale, scale);
      }
    }
    cursor += (CHAR_ADVANCE + tracking) * scale;
  }
}
